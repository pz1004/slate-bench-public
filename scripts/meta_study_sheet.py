"""Write the meta-study verification sheet, or set up and merge the recheck coding.

Without a subcommand, writes docs/meta_study/verification_sheet.md from claims.csv and
screening.csv. Rerun it after editing claims.csv.

The subcommands handle the declared recheck, a third blind AI coding of a subset of cells
(protocol.md, Deviations 8 and 9):

* ``recheck-draw --seed N`` draws the claims coded in full, writes ``recheck_subset.json``,
  and freezes the AI-resolved codes in ``*_ai`` columns;
* ``recheck-sheet`` writes the blank coding files ``recheck_coding.csv`` and
  ``recheck_coding_sheet.md``, which show no earlier code;
* ``recheck-merge`` checks the filled ``recheck_coding.csv``. It writes the third codes
  into ``*_recheck`` and the final columns: the AI-resolved code, or the code a
  disagreement was resolved to against the source (``resolved``, with a
  ``resolution_note``, which becomes the field's evidence pointer).

The check of the codes behind the abstract's counts (protocol.md, Deviations 11 and 12; at
the author's request it was made by fresh Claude sessions, not by the author):

* ``count-check-sheet`` writes ``count_check.csv`` (fixed references and validation
  provenance of every verified claim, with the final code, its evidence pointer and columns
  for the locators prepared for the check) unless it exists, and renders
  ``count_check_sheet.md`` from it;
* ``count-check-merge`` checks the decisions (``agree``, or ``change`` with a code and a
  reason) and writes them into ``*_countcheck`` and ``*_countcheck_note``. A changed code
  becomes the final code, and a note, the reason for a change or the corrected pointer of a
  confirmed code, becomes the field's evidence pointer.
"""

