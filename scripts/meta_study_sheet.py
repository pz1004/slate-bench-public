HEADER = """# Meta-study verification sheet

Generated by `scripts/meta_study_sheet.py` from `claims.csv` and `screening.csv`; rerun it
after editing.

Every claim was coded twice with Claude (Anthropic): a first coding (**Draft**) and a blind
second coding from the source that did not see the first (**Check**). Where the two differ,
the code was resolved against the source text (**AI resolved**, with the reason in the
verification note). A declared subset of the cells was then coded a third time, blind to
both earlier codings (**Recheck**; protocol.md, Deviations 8 and 9). Where the recheck
disagrees, the difference was resolved against the source again, with the reason in
`recheck_coding.csv`. The **Final** code is the AI-resolved code unless that second
resolution changed it, and for a resolved disagreement the evidence pointer is the reason
for the resolution. Final codes that differ from the draft are in bold, and a dagger
marks a final code the recheck resolution changed. No human coder was involved.

To spot-check a claim:

1. **Eligibility.** Check the headline claim against the five criteria in `protocol.md`. If it
   fails, set `verification` to `excluded`, give the reason in `verification_note`, and
   change the record's decision in `screening.csv` to `exclude` with the same reason.
2. **Quoted codes (★).** Check these first: the manuscript quotes their counts, and the
   abstract quotes fixed references and validation provenance.
3. **Remaining codes.** Check them against the operational definitions in `protocol.md`
   (D declared, P partial, A absent, NA not applicable; extras yes, no or unclear).
4. **Record a correction** through the recheck file (`recheck_coding.csv`, then
   `make meta-recheck-merge`). Never edit the `*_draft`, `*_check`, `*_ai` or `*_recheck`
   columns, which the manuscript compares against.

The submission build `make assets META_FLAGS=--meta-verified-only paper check` refuses to
run while any claim is `unverified`, any declared recheck cell is uncoded or any recheck
disagreement is unresolved.
"""


def render(claims: pd.DataFrame, screening: pd.DataFrame, declaration: dict | None = None) -> str:
    lines = [HEADER]
    pending = screening[screening["decision"].eq("not coded")]
    if not pending.empty:
        lines += ["## Records awaiting an eligibility decision", ""]
        for _, record in pending.iterrows():
            lines.append(
                f"- **{record['record_id']}**, {record['title']} ({record['year']}): {record['reason']}. "
                "Apply the five criteria to its abstract and contributions. If it is eligible, add a row "
                "to `claims.csv` and set its decision in `screening.csv` to `include`; otherwise set "
                "`exclude` with the reason."
            )
        lines.append("")
    recheck = all(f"{item}_recheck" in claims.columns for item in ITEMS)
    declared = set(declared_cells(declaration)) if declaration is not None else set()
    if declaration is not None:
        coded = sum(1 for record, item in declared if _value(claims, record, f"{item}_recheck"))
        disagreed = sum(
            1
            for record, item in declared
            if _value(claims, record, f"{item}_recheck")
            and _value(claims, record, f"{item}_recheck") != _value(claims, record, f"{item}_ai")
        )
        changed = sum(1 for record, item in declared if _value(claims, record, item) != _value(claims, record, f"{item}_ai"))
        lines += [
            "## Recheck coding",
            "",
            f"Declared subset: {', '.join(LABELS[item] for item in declaration['all_claims_items'])} for all "
            f"{len(declaration['population'])} verified claims, and every item for "
            f"{', '.join(declaration['full_claims'])} (seed {declaration['seed']}). "
            f"{coded} of {len(declared)} cells coded; the recheck disagreed with {disagreed} AI-resolved codes, "
            f"and resolving those against the sources changed {changed}.",
            "",
        ]
    screen = screening.set_index("record_id")
    lines += ["## Claims", ""]
    for _, claim in claims.iterrows():
        record = str(claim["record_id"])
        url = screen.loc[record, "url"] if record in screen.index else ""
        lines += [
            f"### {record}: {claim['paper']} [{claim['verification']}]",
            "",
            f"Source: {url}",
            "",
            f"Claim coded: {claim['claim_paraphrase']}",
            "",
        ]
        if claim["verification"] == "unverified" and record in NOTES:
            lines += [f"**Note:** {NOTES[record]}", ""]
        if str(claim.get("verification_note", "")):
            lines += [f"**Verification note:** {claim['verification_note']}", ""]
        count_columns = all(f"{item}_countcheck" in claims.columns for item in COUNT_CHECK_ITEMS)
        if recheck and count_columns:
            lines += [
                "| | Field | Draft | Check | AI resolved | Recheck | Count check | Final | Evidence pointer |",
                "|---|---|---|---|---|---|---|---|---|",
            ]
        elif recheck:
            lines += [
                "| | Field | Draft | Check | AI resolved | Recheck | Final | Evidence pointer | OK? |",
                "|---|---|---|---|---|---|---|---|---|",
            ]
        else:
            lines += [
                "| | Field | Draft | Check | Final | Evidence pointer | OK? |",
                "|---|---|---|---|---|---|---|",
            ]
        for column, label, starred, evidence in [
            *[(column, label, column in QUOTED, claim[f"{column}_evidence"]) for column, label in FIELDS],
            *[(column, label, column in QUOTED_EXTRAS, "") for column, label in EXTRAS],
        ]:
            draft = claim.get(f"{column}_draft", "")
            check = claim.get(f"{column}_check", "")
            final = str(claim[column])
            shown = f"**{final}**" if draft and final != draft else final
            star = "★" if starred else ""
            if recheck:
                ai = str(claim.get(f"{column}_ai", ""))
                code = str(claim.get(f"{column}_recheck", ""))
                if final != ai:
                    shown += " †"
                if not code and (record, column) in declared:
                    code = "(to code)"
                if count_columns:
                    counted = str(claim.get(f"{column}_countcheck", "")) if column in COUNT_CHECK_ITEMS else ""
                    if column in COUNT_CHECK_ITEMS and not counted:
                        counted = "(to check)"
                    lines.append(f"| {star} | {label} | {draft} | {check} | {ai} | {code} | {counted} | {shown} | {evidence} |")
                else:
                    lines.append(f"| {star} | {label} | {draft} | {check} | {ai} | {code} | {shown} | {evidence} | [ ] |")
            else:
                lines.append(f"| {star} | {label} | {draft} | {check} | {shown} | {evidence} | [ ] |")
        lines.append("")
    return "\n".join(lines)


def _value(claims: pd.DataFrame, record: str, column: str) -> str:
    if column not in claims.columns:
        return ""
    values = claims.loc[claims["record_id"].eq(record), column]
    return str(values.iloc[0]) if not values.empty else ""


