def _recheck_entries(directory: Path) -> dict[tuple[str, str], pd.Series]:
    path = directory / RECHECK_CODING_FILE
    if not path.exists():
        return {}
    sheet = pd.read_csv(path, keep_default_na=False, dtype=str)
    return {(str(row["record_id"]).strip(), str(row["item"]).strip()): row for _, row in sheet.iterrows()}


def _render_count_check_sheet(directory: Path, sheet: pd.DataFrame) -> None:
    protocol = (directory / "protocol.md").read_text(encoding="utf-8")
    lines = [
        "# Check of the codes behind the abstract's counts",
        "",
        f"Generated by `scripts/meta_study_sheet.py count-check-sheet` from `{COUNT_CHECK_FILE}`; the",
        "decisions go into that file (protocol.md, Deviations 11 and 12). At the author's request the",
        "check was made by fresh Claude sessions, not by the author; no human coder was involved.",
        "",
        f"The {len(sheet)} cells below are the fixed-references and validation-provenance codes of every",
        "coded claim, the codes whose counts the abstract reports. Each was coded by AI (three codings",
        "for these two fields, with disagreements resolved against the source). For each cell:",
        "",
        "1. Open the paper at the locators given and read the passages they point to. The locators",
        "   and paraphrases were prepared by Claude from the papers; no text is copied.",
        "2. Decide under the coding scheme and conventions at the end of this sheet whether the code",
        "   holds. Points that need attention are listed.",
        f"3. In `{COUNT_CHECK_FILE}`, set `decision` to `agree`, or to `change` with the correct code",
        "   in `check_code` and the reason, with its locator, in `check_note`.",
        "",
        "Then run `make meta-count-merge`; `make meta-count-check` reports progress without writing.",
        "",
    ]
    for record, group in sheet.groupby("record_id", sort=True):
        first = group.iloc[0]
        lines += [
            f"## {record}: {first['paper']}",
            "",
            f"{first['title']}, {first['url']}",
            "",
            f"Claim coded: {first['claim']}",
            "",
        ]
        for _, cell in group.iterrows():
            lines += [
                f"### {cell['item_label']}: {cell['code']} ({cell['allowed']})",
                "",
                f"- **Evidence pointer of the code:** {cell['evidence'] or '(none)'}",
                f"- **Locators:** {cell['locator'] or '(to be prepared)'}",
                f"- **What the passages say:** {cell['paraphrase'] or '(to be prepared)'}",
            ]
            if str(cell["attention"]).strip():
                lines.append(f"- **Attention:** {cell['attention']}")
            if str(cell["first_code"]).strip():
                lines.append(f"- **Checker's first code, before it saw the code under check:** {cell['first_code']}")
            if str(cell.get("checker_reason", "")).strip():
                lines.append(f"- **Checker's reason:** {cell['checker_reason']}")
            decision = str(cell["decision"]).strip()
            if decision:
                shown = f"{decision} {cell['check_code']}".strip()
                lines.append(f"- **Decision:** {shown}" + (f" ({cell['check_note']})" if cell["check_note"] else ""))
            lines.append("")
    lines.append(_protocol_excerpt(protocol))
    (directory / COUNT_CHECK_SHEET_FILE).write_text("\n".join(lines), encoding="utf-8")


def count_check_sheet(directory: Path, *, reset: bool) -> None:
    """Write the count-check file unless it exists, then render the readable sheet from it."""
    path = directory / COUNT_CHECK_FILE
    claims = read_claims(directory / "claims.csv")
    if path.exists() and not reset:
        sheet = pd.read_csv(path, keep_default_na=False, dtype=str)
    else:
        if path.exists():
            existing = pd.read_csv(path, keep_default_na=False, dtype=str)
            if existing[COUNT_CHECK_COLUMNS].apply(lambda column: column.str.strip().ne("")).any().any():
                raise SystemExit(f"{path} holds decisions; it is not reset")
        verified = claims[claims["verification"].eq("verified")].set_index("record_id")
        screening = pd.read_csv(directory / "screening.csv", keep_default_na=False, dtype=str).set_index("record_id")
        recheck = _recheck_entries(directory)
        rows = []
        for record, item in count_check_cells(verified.index):
            code, evidence = recheck_final(verified.loc[record], item, recheck.get((record, item)))
            rows.append({
                "record_id": record,
                "paper": verified.at[record, "paper"],
                "title": screening.at[record, "title"],
                "url": screening.at[record, "url"],
                "claim": verified.at[record, "claim_paraphrase"],
                "item": item,
                "item_label": LABELS[item],
                "allowed": "/".join(allowed_codes(item)),
                "code": code,
                "evidence": evidence,
                "locator": "",
                "paraphrase": "",
                "attention": "",
                "first_code": "",
                "decision": "",
                "check_code": "",
                "check_note": "",
            })
        sheet = pd.DataFrame(rows, columns=COUNT_CHECK_SHEET_COLUMNS)
        sheet.to_csv(path, index=False)
        print(f"Wrote {path} ({len(sheet)} cells)")
    _render_count_check_sheet(directory, sheet)
    print(f"Wrote {directory / COUNT_CHECK_SHEET_FILE}")


def count_check_merge(directory: Path, *, dry_run: bool) -> None:
    """Check the count check's decisions and write them into claims.csv."""
    path = directory / COUNT_CHECK_FILE
    if not path.exists():
        raise SystemExit(f"No {COUNT_CHECK_FILE}; run `make meta-count-sheet` first")
    sheet = pd.read_csv(path, keep_default_na=False, dtype=str)
    claims_path = directory / "claims.csv"
    claims = read_claims(claims_path)
    problems = [f"{COUNT_CHECK_FILE} has no '{column}' column" for column in COUNT_CHECK_SHEET_COLUMNS if column not in sheet]
    if problems:
        raise SystemExit("\n".join(problems))
    verified = claims[claims["verification"].eq("verified")].set_index("record_id")
    recheck = _recheck_entries(directory)
    cells = list(zip(sheet["record_id"].str.strip(), sheet["item"].str.strip()))
    expected = count_check_cells(verified.index)
    duplicates = sorted({cell for cell in cells if cells.count(cell) > 1})
    if duplicates:
        problems.append(f"duplicate cells: {[f'{r}:{i}' for r, i in duplicates]}")
    if sorted(set(cells)) != sorted(expected):
        missing = sorted(set(expected) - set(cells))
        extra = sorted(set(cells) - set(expected))
        problems.append(f"the cells are not those of the check; missing {missing}, unexpected {extra}")
    decisions: dict[tuple[str, str], tuple[str, str]] = {}
    for cell, (_, entry) in zip(cells, sheet.iterrows()):
        record, item = cell
        if cell not in set(expected):
            continue
        before, _ = recheck_final(verified.loc[record], item, recheck.get(cell))
        if normalize_code(item, entry["code"]) != before:
            problems.append(f"{record}:{item} shows the code {entry['code']!r}, but the code under check is {before!r}")
        decision = str(entry["decision"]).strip().lower()
        code = normalize_code(item, entry["check_code"])
        note = str(entry["check_note"]).strip()
        first = normalize_code(item, entry["first_code"])
        if not decision:
            if code or note:
                problems.append(f"{record}:{item} has a check code or note but no decision")
            continue
        if first not in allowed_codes(item):
            problems.append(f"{record}:{item} has no valid first code ({entry['first_code']!r})")
        if decision not in COUNT_CHECK_DECISIONS:
            problems.append(f"{record}:{item} has the decision {entry['decision']!r}; allowed: {'/'.join(COUNT_CHECK_DECISIONS)}")
        elif decision == "change":
            if code not in allowed_codes(item) or code == before:
                problems.append(f"{record}:{item} is changed to {entry['check_code']!r}, not another allowed code")
            if not note:
                problems.append(f"{record}:{item} is changed without a reason in check_note")
            decisions[cell] = (code, note)
        else:
            if code and code != before:
                problems.append(f"{record}:{item} agrees but gives the other code {entry['check_code']!r}")
            decisions[cell] = (before, note)
    if problems:
        raise SystemExit(f"{COUNT_CHECK_FILE} is not valid:\n- " + "\n- ".join(problems))
    print(f"{len(decisions)} of {len(expected)} cells decided; {sum(code != recheck_final(verified.loc[r], i, recheck.get((r, i)))[0] for (r, i), (code, _) in decisions.items())} changed")
    if dry_run:
        return
    index = {record: position for position, record in enumerate(claims["record_id"])}
    for item in COUNT_CHECK_ITEMS:
        for column in [f"{item}_countcheck", f"{item}_countcheck_note"]:
            if column not in claims.columns:
                claims[column] = ""
    for record, item in expected:
        row = index[record]
        before, evidence = recheck_final(claims.loc[row], item, recheck.get((record, item)))
        code, note = decisions.get((record, item), ("", ""))
        claims.at[row, f"{item}_countcheck"] = code
        claims.at[row, f"{item}_countcheck_note"] = note
        changed = bool(code) and code != before
        claims.at[row, item] = code if changed else before
        if item in FIELD_COLUMNS:
            # A note is the reason for a change or the corrected pointer of a confirmed code.
            claims.at[row, f"{item}_evidence"] = note if note else evidence
    declaration = load_declaration(directory)
    recheck_sheet = pd.read_csv(directory / RECHECK_CODING_FILE, keep_default_na=False, dtype=str) if declaration else None
    check_recheck_state(claims, declaration, sheet=recheck_sheet, require_complete=False)
    check_count_check_state(claims, require_complete=False)
    claims.to_csv(claims_path, index=False)
    print(f"Merged into {claims_path}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--directory", type=Path, default=Path("docs/meta_study"))
    commands = parser.add_subparsers(dest="command", required=False)
    draw = commands.add_parser("recheck-draw", help="draw the claims coded in full and freeze the AI codes")
    draw.add_argument("--seed", type=int, required=True)
    draw.add_argument("--full", type=int, default=4, help="number of claims coded on every item")
    sheet = commands.add_parser("recheck-sheet", help="write the blank, blind coding files")
    sheet.add_argument("--force", action="store_true", help="overwrite a coding file that already holds codes")
    merge = commands.add_parser("recheck-merge", help="check the filled coding file and merge it into claims.csv")
    merge.add_argument("--dry-run", action="store_true", help="check and report progress without writing")
    count_sheet = commands.add_parser("count-check-sheet", help="write the count-check file and its readable sheet")
    count_sheet.add_argument("--reset", action="store_true", help="recreate the check file (refused once decisions exist)")
    count_merge = commands.add_parser("count-check-merge", help="check the count check's decisions and merge them")
    count_merge.add_argument("--dry-run", action="store_true", help="check and report progress without writing")
    args = parser.parse_args()
    if args.command == "recheck-draw":
        recheck_draw(args.directory, args.seed, args.full)
    elif args.command == "recheck-sheet":
        recheck_sheet(args.directory, force=args.force)
    elif args.command == "recheck-merge":
        recheck_merge(args.directory, dry_run=args.dry_run)
        if args.dry_run:
            return
    elif args.command == "count-check-sheet":
        count_check_sheet(args.directory, reset=args.reset)
        return
    elif args.command == "count-check-merge":
        count_check_merge(args.directory, dry_run=args.dry_run)
        if args.dry_run:
            return
    write_sheet(args.directory)


if __name__ == "__main__":
    main()
