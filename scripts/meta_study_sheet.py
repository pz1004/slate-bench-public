def recheck_draw(directory: Path, seed: int, n_full: int) -> dict:
    """Draw the claims coded in full, write the declaration and freeze the AI-resolved codes."""
    path = directory / RECHECK_SUBSET_FILE
    if path.exists():
        raise SystemExit(f"{path} exists; the draw is declared once and never redone")
    claims_path = directory / "claims.csv"
    claims = read_claims(claims_path)
    frozen = (
        [f"{item}_ai" for item in ITEMS]
        + [f"{field}_evidence_ai" for field in FIELD_COLUMNS]
        + [f"{item}_recheck" for item in ITEMS]
    )
    present = [column for column in frozen if column in claims.columns]
    if present:
        raise SystemExit(f"claims.csv already has the columns {present}")
    population = sorted(claims.loc[claims["verification"].eq("verified"), "record_id"])
    if (claims["verification"] == "unverified").any():
        raise SystemExit("Every claim must be verified or excluded before the recheck subset is drawn")
    declaration = {
        "recorded": dt.date.today().isoformat(),
        "coder": "Claude (Anthropic): a third AI coding, blind to the first two",
        "population": population,
        "all_claims_items": list(RECHECK_ALL_CLAIM_ITEMS),
        "full_claims_items": "all items",
        "seed": int(seed),
        "n_full": int(n_full),
        "rule": DRAW_RULE,
        "full_claims": draw_full_claims(population, seed, n_full),
    }
    declaration["n_cells"] = len(declared_cells(declaration))
    declaration["ai_codes_sha256"] = ai_codes_digest(claims, population)
    for item in ITEMS:
        claims[f"{item}_ai"] = claims[item]
    for field in FIELD_COLUMNS:
        claims[f"{field}_evidence_ai"] = claims[f"{field}_evidence"]
    for item in ITEMS:
        claims[f"{item}_recheck"] = ""
    claims.to_csv(claims_path, index=False)
    path.write_text(json.dumps(declaration, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {path}: {declaration['n_cells']} cells; coded in full: {', '.join(declaration['full_claims'])}")
    return declaration


def _protocol_excerpt(protocol: str) -> str:
    """The coding scheme and the conventions of Deviation 6, verbatim from protocol.md."""
    scheme = re.search(r"^## Coding scheme\n(.*?)^## ", protocol, flags=re.DOTALL | re.MULTILINE)
    conventions = re.search(r"^6\. \*\*Conventions.*?(?=^7\. )", protocol, flags=re.DOTALL | re.MULTILINE)
    if scheme is None or conventions is None:
        raise SystemExit("protocol.md no longer has the 'Coding scheme' section or Deviation 6")
    return (
        "## Coding scheme (from protocol.md)\n\n" + scheme.group(1).strip() + "\n\n"
        "## Conventions (protocol.md, Deviation 6)\n\n" + conventions.group(0).strip() + "\n"
    )


def recheck_sheet(directory: Path, *, force: bool) -> None:
    """Write the blank coding files. They show no earlier code, evidence pointer or note."""
    declaration = load_declaration(directory)
    if declaration is None:
        raise SystemExit(f"No {RECHECK_SUBSET_FILE}; run `make meta-recheck-draw` first")
    csv_path = directory / RECHECK_CODING_FILE
    if csv_path.exists() and not force:
        existing = pd.read_csv(csv_path, keep_default_na=False, dtype=str)
        if "code" in existing.columns and existing["code"].str.strip().ne("").any():
            raise SystemExit(f"{csv_path} already holds codes; pass --force to overwrite it")
    claims = read_claims(directory / "claims.csv").set_index("record_id")
    screening = pd.read_csv(directory / "screening.csv", keep_default_na=False, dtype=str).set_index("record_id")
    rows = []
    for record, item in declared_cells(declaration):
        rows.append({
            "record_id": record,
            "paper": claims.at[record, "paper"],
            "title": screening.at[record, "title"],
            "year": screening.at[record, "year"],
            "url": screening.at[record, "url"],
            "claim": claims.at[record, "claim_paraphrase"],
            "item": item,
            "item_label": LABELS[item],
            "allowed": "/".join(allowed_codes(item)),
            "code": "",
            "pointer": "",
            "note": "",
            "resolved": "",
            "resolution_note": "",
        })
    pd.DataFrame(rows, columns=SHEET_COLUMNS).to_csv(csv_path, index=False)
    protocol = (directory / "protocol.md").read_text(encoding="utf-8")
    lines = [
        "# Recheck coding sheet",
        "",
        f"Generated by `scripts/meta_study_sheet.py recheck-sheet` from `{RECHECK_SUBSET_FILE}`. It shows no",
        "earlier code, evidence pointer or note.",
        "",
        f"Code {len(rows)} cells: {', '.join(LABELS[item] for item in declaration['all_claims_items'])} for every",
        f"claim below, and every item for {', '.join(declaration['full_claims'])}. For each cell, read the",
        "paper's headline claim (quoted below) and apply the definitions and conventions at the end",
        "of this sheet. Enter the code in the `code` column of",
        f"`{RECHECK_CODING_FILE}`, the section, table or figure that supports it in `pointer`, and",
        "anything worth recording in `note`. Then run `make meta-recheck-merge`; `make meta-recheck-check`",
        "reports progress without writing anything.",
        "",
        "## Claims",
        "",
    ]
    for record in sorted(declaration["population"]):
        items = [item for cell_record, item in declared_cells(declaration) if cell_record == record]
        lines += [
            f"### {record}: {claims.at[record, 'paper']}",
            "",
            f"{screening.at[record, 'title']} ({screening.at[record, 'year']}), {screening.at[record, 'url']}",
            "",
            f"Claim to code: {claims.at[record, 'claim_paraphrase']}",
            "",
            "Items: " + "; ".join(f"{LABELS[item]} ({'/'.join(allowed_codes(item))})" for item in items),
            "",
        ]
    lines.append(_protocol_excerpt(protocol))
    (directory / RECHECK_SHEET_FILE).write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {csv_path} ({len(rows)} cells) and {directory / RECHECK_SHEET_FILE}")


def recheck_merge(directory: Path, *, dry_run: bool) -> None:
    """Check the filled coding file and write the recheck and final codes into claims.csv."""
    declaration = load_declaration(directory)
    if declaration is None:
        raise SystemExit(f"No {RECHECK_SUBSET_FILE}; run `make meta-recheck-draw` first")
    sheet = pd.read_csv(directory / RECHECK_CODING_FILE, keep_default_na=False, dtype=str)
    claims_path = directory / "claims.csv"
    claims = read_claims(claims_path)
    problems: list[str] = []
    for column in ["record_id", "item", "code", "resolved", "resolution_note"]:
        if column not in sheet.columns:
            problems.append(f"{RECHECK_CODING_FILE} has no '{column}' column")
    if problems:
        raise SystemExit("\n".join(problems))
    cells = list(zip(sheet["record_id"].str.strip(), sheet["item"].str.strip()))
    duplicates = sorted({cell for cell in cells if cells.count(cell) > 1})
    if duplicates:
        problems.append(f"duplicate cells: {[f'{r}:{i}' for r, i in duplicates]}")
    declared = declared_cells(declaration)
    extra = sorted(set(cells) - set(declared))
    absent = sorted(set(declared) - set(cells))
    if extra:
        problems.append(f"cells that are not declared: {[f'{r}:{i}' for r, i in extra]}")
    if absent:
        problems.append(f"declared cells missing from the file: {[f'{r}:{i}' for r, i in absent]}")
    verified = set(claims.loc[claims["verification"].eq("verified"), "record_id"])
    codes: dict[tuple[str, str], tuple[str, str, str]] = {}
    for (record, item), raw, raw_resolved, note in zip(cells, sheet["code"], sheet["resolved"], sheet["resolution_note"]):
        if record not in verified:
            problems.append(f"{record} is not a verified claim")
            continue
        if item not in ITEMS:
            continue
        code = normalize_code(item, raw)
        resolved = normalize_code(item, raw_resolved)
        for label, value, original in [("code", code, raw), ("resolved code", resolved, raw_resolved)]:
            if value and value not in allowed_codes(item):
                problems.append(f"{record}:{item} has the {label} {original!r}; allowed: {'/'.join(allowed_codes(item))}")
        codes[(record, item)] = (code, resolved, str(note).strip())
    if problems:
        raise SystemExit("recheck_coding.csv is not valid:\n- " + "\n- ".join(problems))
    coded = sum(1 for code, _, _ in codes.values() if code)
    print(f"{coded} of {len(declared)} declared cells coded")
    if dry_run:
        return
    index = {record: position for position, record in enumerate(claims["record_id"])}
    for (record, item), (code, resolved, note) in codes.items():
        row = index[record]
        ai = claims.at[row, f"{item}_ai"]
        claims.at[row, f"{item}_recheck"] = code
        by_resolution = bool(code and code != ai and resolved and note)
        claims.at[row, item] = resolved if by_resolution else ai
        if item in FIELD_COLUMNS:
            # A resolved disagreement's evidence is the reason it was resolved.
            claims.at[row, f"{item}_evidence"] = note if by_resolution else claims.at[row, f"{item}_evidence_ai"]
        # A code the count check changed stays changed, and a check note stays the evidence
        # (protocol.md, Deviations 11 and 12).
        counted = str(claims.at[row, f"{item}_countcheck"]) if f"{item}_countcheck" in claims.columns else ""
        counted_note = str(claims.at[row, f"{item}_countcheck_note"]) if counted else ""
        if counted and counted != claims.at[row, item]:
            claims.at[row, item] = counted
        if counted and counted_note and item in FIELD_COLUMNS:
            claims.at[row, f"{item}_evidence"] = counted_note
    check_recheck_state(claims, declaration, sheet=sheet, require_complete=False)
    claims.to_csv(claims_path, index=False)
    print(f"Merged into {claims_path}")


